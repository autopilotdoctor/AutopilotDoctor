  function renderFindings() {
    const query = document.getElementById('search-box').value.toLowerCase().trim();
    const sevFilter = document.getElementById('severity-filter').value;
    const modFilter = document.getElementById('module-filter').value;

    const severityOrder = { Critical: 1, Warning: 2, Pass: 3, Info: 4 };
    const filtered = (payload.findings || [])
      .filter(f => sevFilter === 'ALL' || f.severity === sevFilter)
      .filter(f => modFilter === 'ALL' || f.module === modFilter)
      .filter(f => !query || JSON.stringify(f).toLowerCase().includes(query))
      .sort((a, b) => (severityOrder[a.severity] || 9) - (severityOrder[b.severity] || 9));

    const container = document.getElementById('finding-list');
    if (filtered.length === 0) {
      container.innerHTML = `<div class="section-card" style="text-align:center;color:var(--text-muted);">No diagnostic findings match the current filter criteria.</div>`;
      return;
    }

    container.innerHTML = filtered.map(f => {
      const hasFix = f.remediationHint && f.remediationHint !== 'None';
      const fixHtml = hasFix ? `
        <div class="remediation-box">
          <div class="remediation-text"><strong>Remediation:</strong> ${escapeHtml(f.remediationHint)}</div>
          <button class="copy-btn" onclick="copyHint(this, ${escapeHtml(JSON.stringify(f.remediationHint))})">Copy Fix</button>
        </div>` : '';

      return `
        <div class="finding-card ${escapeHtml(f.severity)}">
          <div class="finding-header">
            <div class="finding-title-group">
              <span class="badge badge-${escapeHtml(f.severity)}">${escapeHtml(f.severity)}</span>
              <span class="badge badge-mod">${escapeHtml(f.module)} &bull; ${escapeHtml(f.checkId)}</span>
              <span class="finding-title">${escapeHtml(f.title)}</span>
            </div>
            <span class="observed-pill">${escapeHtml(f.observedValue)}</span>
          </div>
          <div class="finding-summary">${escapeHtml(f.summary)}</div>
          ${fixHtml}
        </div>
      `;
    }).join('');
  }

