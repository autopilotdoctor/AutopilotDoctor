<script>
  const payload = JSON.parse(document.getElementById('diagnostic-data').textContent);

  function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  function toggleTheme() {
    const html = document.documentElement;
    const current = html.getAttribute('data-theme');
    const next = current === 'dark' ? 'light' : 'dark';
    html.setAttribute('data-theme', next);
    document.getElementById('theme-btn').textContent = next === 'dark' ? 'Light Mode' : 'Dark Mode';
  }

  function switchTab(tabId, btnEl) {
    document.querySelectorAll('.tab-panel').forEach(p => p.classList.remove('active'));
    document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
    document.getElementById(tabId).classList.add('active');
    btnEl.classList.add('active');
  }

  function downloadJson() {
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `AutopilotDoctor-${payload.system.hostname || 'report'}.json`;
    a.click();
    URL.revokeObjectURL(url);
  }

  function copyHint(btn, text) {
    navigator.clipboard.writeText(text).then(() => {
      const orig = btn.textContent;
      btn.textContent = 'Copied!';
      setTimeout(() => { btn.textContent = orig; }, 1500);
    });
  }

  function filterByKpi(sev) {
    switchTab('tab-findings', document.querySelector('.tab-btn'));
    document.getElementById('severity-filter').value = sev;
    renderFindings();
  }

  function initHeaderAndMeta() {
    const m = payload.meta || {};
    const s = payload.system || {};
    document.getElementById('report-meta-subtitle').textContent =
      `Schema v${m.schemaVersion || '1.0'} \u2022 Generated ${m.generatedAtUtc || ''} \u2022 ${m.anonymized ? 'Anonymized Mode' : 'Full Identifiers'}`;

    if (!m.isAdmin) {
      document.getElementById('admin-banner').style.display = 'flex';
    }

    const sysItems = [
      { label: 'Hostname', val: s.hostname || 'N/A' },
      { label: 'Hardware Model', val: `${s.manufacturer || ''} ${s.model || ''}`.trim() || 'N/A' },
      { label: 'Operating System', val: s.osCaption || 'N/A' },
      { label: 'OS Build', val: s.osBuild || 'N/A' },
      { label: 'System Uptime', val: `${s.uptimeHours ?? 0} Hours` },
      { label: 'Execution Context', val: m.isAdmin ? 'Administrator (Elevated)' : 'Standard User' }
    ];

    document.getElementById('sys-grid').innerHTML = sysItems.map(i => `
      <div class="sys-item">
        <div class="sys-label">${escapeHtml(i.label)}</div>
        <div class="sys-val">${escapeHtml(i.val)}</div>
      </div>
    `).join('');
  }

  function initKpis() {
    const sum = payload.summary || {};
    const overallBadgeClass = sum.overallHealth === 'Critical' ? 'badge-Critical'
      : sum.overallHealth === 'Warning' ? 'badge-Warning' : 'badge-Pass';

    document.getElementById('kpi-grid').innerHTML = `
      <div class="kpi-card" onclick="filterByKpi('ALL')">
        <div class="kpi-title">Overall Readiness</div>
        <div style="margin-top:0.55rem;"><span class="badge ${overallBadgeClass}" style="font-size:1.05rem;padding:0.35rem 0.75rem;">${escapeHtml(sum.overallHealth || 'Unknown')}</span></div>
      </div>
      <div class="kpi-card kpi-crit" onclick="filterByKpi('Critical')">
        <div class="kpi-title">Critical Issues</div>
        <div class="kpi-num">${sum.criticalCount ?? 0}</div>
      </div>
      <div class="kpi-card kpi-warn" onclick="filterByKpi('Warning')">
        <div class="kpi-title">Warnings</div>
        <div class="kpi-num">${sum.warningCount ?? 0}</div>
      </div>
      <div class="kpi-card kpi-pass" onclick="filterByKpi('Pass')">
        <div class="kpi-title">Passed Checks</div>
        <div class="kpi-num">${sum.passCount ?? 0}</div>
      </div>
      <div class="kpi-card kpi-info" onclick="filterByKpi('Info')">
        <div class="kpi-title">Informational</div>
        <div class="kpi-num">${sum.infoCount ?? 0}</div>
      </div>
    `;
